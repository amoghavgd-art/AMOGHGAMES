import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");

const runtimePath = path.join(rootDir, "engine", "runtime.js");
const rawRuntimeSource = fs.readFileSync(runtimePath, "utf8").trim();
const runtimeCode = rawRuntimeSource.replace(/^export\s+/gm, "");

const hostHtml = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline' blob:">
<title>playglow-cart</title>
</head>
<body>
<script type="module">
// Inlined playglow cart engine runtime (generated by scripts/build-cart.mjs)
${runtimeCode}

// Pool of 3 RGBA ArrayBuffers (320 * 200 * 4 = 256,000 bytes)
const FRAME_BYTES = W * H * 4;
const bufferPool = [
  new ArrayBuffer(FRAME_BYTES),
  new ArrayBuffer(FRAME_BYTES),
  new ArrayBuffer(FRAME_BYTES),
];

let runner = null;
let frozen = false;
let activeLoadId = 0;
let completedLoadId = 0;
let consecutiveErrors = 0;
let accumMs = 0;

function post(type, payload = {}, transfer = []) {
  parent.postMessage({ type, ...payload }, "*", transfer);
}

// Lock down forbidden globals in the iframe before any dynamic blob import
function applySandboxPrelude() {
  try { delete Math.random; } catch {}
  for (const name of ["Date", "eval", "Function", "setTimeout", "setInterval", "fetch", "WebSocket", "XMLHttpRequest"]) {
    try { Object.defineProperty(globalThis, name, { value: undefined, writable: false, configurable: true }); } catch {}
  }
}

addEventListener("message", async (e) => {
  if (e.source !== parent) return;
  const msg = e.data;
  if (!msg || typeof msg.type !== "string") return;

  if (msg.type === "return") {
    if (msg.rgba instanceof ArrayBuffer && msg.rgba.byteLength === FRAME_BYTES) {
      bufferPool.push(msg.rgba);
    }
    return;
  }

  if (msg.type === "load") {
    const reqId = Number(msg.loadId) || 0;
    if (reqId > 0) {
      if (reqId === completedLoadId && runner && !frozen) {
        post("ready", { title: msg.card?.title || "PLAYGLOW", loadId: reqId });
        return;
      }
      if (reqId === activeLoadId) return;
      activeLoadId = reqId;
    } else if (activeLoadId === -1) {
      return;
    } else {
      activeLoadId = -1;
    }

    frozen = false;
    consecutiveErrors = 0;
    accumMs = 0;
    const { source, card, seed = 7, save = {} } = msg;

    const scan = scanSource(source);
    if (!scan.ok) {
      if (reqId === 0) activeLoadId = 0;
      frozen = true;
      post("error", { phase: "load", message: scan.issues.join("; "), stack: "", loadId: reqId });
      return;
    }

    try {
      const blob = new Blob([source], { type: "text/javascript" });
      const url = URL.createObjectURL(blob);
      applySandboxPrelude();
      let mod;
      try {
        mod = await import(url);
      } finally {
        URL.revokeObjectURL(url);
      }

      if (reqId > 0 && reqId !== activeLoadId) return;

      const createFn = typeof mod.create === "function" ? mod.create : typeof mod.default === "function" ? mod.default : null;
      if (typeof createFn !== "function") {
        throw new Error("Game module must export function create(engine, card)");
      }

      runner = createCartRunner({
        card,
        seed,
        initialSave: save,
        onSfx: ({ name, note }) => post("sfx", { name, note }),
        onFx: (fx) => post("fx", fx),
        onScore: ({ score, lives }) => post("score", { score, lives }),
        onSave: ({ key, value }) => post("save", { key, value }),
        onGameOver: ({ score, best, reason }) => post("gameover", { score, best, reason }),
        onError: ({ phase, message, stack }) => {
          consecutiveErrors++;
          post("error", { phase, message, stack, loadId: reqId });
          if (phase === "load" || consecutiveErrors >= 3) {
            frozen = true;
          }
        },
      });

      runner.setCreateFn(createFn);
      if (reqId > 0) {
        completedLoadId = reqId;
      } else {
        activeLoadId = 0;
      }
      if (!frozen) {
        post("ready", { title: card?.title || "PLAYGLOW", loadId: reqId });
      }
    } catch (err) {
      if (reqId > 0 && reqId !== activeLoadId) return;
      if (reqId === 0) activeLoadId = 0;
      frozen = true;
      post("error", { phase: "load", message: err?.message || String(err), stack: err?.stack || "", loadId: reqId });
    }
    return;
  }

  if (!runner || frozen) return;

  if (msg.type === "pause") {
    runner.setPaused(true);
    return;
  }
  if (msg.type === "resume") {
    runner.setPaused(false);
    return;
  }
  if (msg.type === "reset") {
    runner.reset();
    return;
  }

  if (msg.type === "tick") {
    const dtMs = Math.max(0, Math.min(100, Number(msg.dt_ms) || 16.6667));
    const input = msg.input || {};
    accumMs += dtMs;
    const stepMs = 1000 / 60;
    let steps = 0;
    // Always run at least 1 step on a tick if accumMs is close to a frame, up to 4 fixed updates
    if (accumMs < stepMs * 0.5) {
      accumMs = stepMs;
    }
    while (accumMs >= stepMs * 0.85 && steps < 4 && !frozen) {
      runner.stepTick(input);
      accumMs -= stepMs;
      if (accumMs < 0) accumMs = 0;
      steps++;
    }
    if (!frozen) {
      runner.render();
      consecutiveErrors = 0;
      const buf = bufferPool.pop() || new ArrayBuffer(FRAME_BYTES);
      runner.writeRgba(new Uint8Array(buf));
      post("frame", { rgba: buf }, [buf]);
    }
  }
});

post("host-ready");
</script>
</body>
</html>
`;

const outDir = path.join(rootDir, "public", "cart");
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "host.html"), hostHtml, "utf8");

// Sync inlined runtime into engine/headless.mjs so it stays 100% standalone with zero drift
const headlessPath = path.join(rootDir, "engine", "headless.mjs");
if (fs.existsSync(headlessPath)) {
  const headlessSrc = fs.readFileSync(headlessPath, "utf8");
  const startMarker = "// BEGIN INLINED RUNTIME";
  const endMarker = "// END INLINED RUNTIME";
  const sIdx = headlessSrc.indexOf(startMarker);
  const eIdx = headlessSrc.indexOf(endMarker);
  if (sIdx !== -1 && eIdx !== -1 && eIdx > sIdx) {
    const updatedHeadless =
      headlessSrc.slice(0, sIdx + startMarker.length) +
      "\n" +
      rawRuntimeSource +
      "\n" +
      headlessSrc.slice(eIdx);
    fs.writeFileSync(headlessPath, updatedHeadless, "utf8");
  }
}

// Sync house games and core engine files across public/house-games/, skill reference, and agent/workspace/engine/
const houseDir = path.join(rootDir, "public", "house-games");
fs.mkdirSync(houseDir, { recursive: true });
const refDir = path.join(
  rootDir,
  "agent",
  ".agents",
  "skills",
  "pixel-game-from-card",
  "reference",
);
fs.mkdirSync(refDir, { recursive: true });
const wsEngineDir = path.join(rootDir, "agent", "workspace", "engine");
const wsGamesDir = path.join(wsEngineDir, "games");
fs.mkdirSync(wsGamesDir, { recursive: true });

// Sync cart.d.ts, runtime.js, and headless.mjs into agent/workspace/engine/ and skill reference
const cartDtsPath = path.join(rootDir, "engine", "cart.d.ts");
if (fs.existsSync(cartDtsPath)) {
  fs.copyFileSync(cartDtsPath, path.join(refDir, "cart.d.ts"));
}
for (const engineFile of ["cart.d.ts", "runtime.js", "headless.mjs"]) {
  const srcEngineFile = path.join(rootDir, "engine", engineFile);
  if (fs.existsSync(srcEngineFile)) {
    fs.copyFileSync(srcEngineFile, path.join(wsEngineDir, engineFile));
  }
}

const gamesDir = path.join(rootDir, "engine", "games");
if (fs.existsSync(gamesDir)) {
  for (const file of fs.readdirSync(gamesDir)) {
    if (file.endsWith(".js")) {
      const srcFile = path.join(gamesDir, file);
      fs.copyFileSync(srcFile, path.join(houseDir, file));
      fs.copyFileSync(srcFile, path.join(refDir, file));
      fs.copyFileSync(srcFile, path.join(wsGamesDir, file));
    }
  }
}

console.log(
  "[build-cart] Wrote public/cart/host.html, synced engine/headless.mjs runtime, and synced engine + house games",
);
